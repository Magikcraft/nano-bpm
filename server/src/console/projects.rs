/// Lowercases and hyphen-slugs a project name into a manifest `id` matching the
/// schema pattern `^[a-z0-9]+(?:-[a-z0-9]+)*$`. Falls back to `app` if empty.
fn slugify_app_id(name: &str) -> String {
    let mut out = String::new();
    let mut prev_dash = false;
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            prev_dash = false;
        } else if !prev_dash && !out.is_empty() {
            out.push('-');
            prev_dash = true;
        }
    }
    let trimmed = out.trim_matches('-');
    if trimmed.is_empty() {
        "app".to_string()
    } else {
        trimmed.to_string()
    }
}
/// overwriting any prior copy so project code imports the current version.
pub fn ensure_project_sdk(name: &str) -> std::io::Result<()> {
    let dir = project_dir(name).ok_or_else(|| {
        std::io::Error::new(std::io::ErrorKind::InvalidInput, "invalid project name")
    })?;
    let nano = dir.join(GEN_DIR);
    std::fs::create_dir_all(&nano)?;
    std::fs::write(nano.join("data-sdk.ts"), DATA_SDK_TS)?;
    std::fs::write(nano.join("app-pages.ts"), APP_PAGES_TS)?;
    std::fs::write(nano.join("data-cli.ts"), DATA_CLI_TS)?;
    std::fs::write(nano.join("domain-types.ts"), DOMAIN_TYPES_TS)?;
    // Seed the typed data-object accessor only when absent, so a reified,
    // per-table `domain.ts` (written by the `domaintypes` op) is not clobbered by
    // SDK re-materialisation (ADR 0029 §6).
    let domain_ts = nano.join("domain.ts");
    if !domain_ts.exists() {
        std::fs::write(&domain_ts, DOMAIN_TS_STUB)?;
    }
    // The typed `defineWorker` wrapper (ADR 0033 §3) is static — write it every
    // run like the rest of the SDK. Its IO map (`worker-io.d.ts`) is reified by the
    // `domaintypes` op, so seed it only when absent (mirrors `domain.ts`) so the
    // wrapper's type import resolves before the first reification.
    std::fs::write(nano.join("workers.ts"), WORKERS_TS)?;
    let workers_dts = nano.join("worker-io.d.ts");
    if !workers_dts.exists() {
        std::fs::write(&workers_dts, WORKERS_DTS_STUB)?;
    }
    // The typed `publishMessage` wrapper (ADR 0040 slice 2) is static — write it
    // every run; its payload map (`message-io.d.ts`) is reified by the
    // `domaintypes` op, so seed it only when absent (mirrors `worker-io.d.ts`).
    std::fs::write(nano.join("messages.ts"), MESSAGES_TS)?;
    let messages_dts = nano.join("message-io.d.ts");
    if !messages_dts.exists() {
        std::fs::write(&messages_dts, MESSAGES_DTS_STUB)?;
    }
    // The typed model-metadata accessor (`@nanobpm/meta`, ADR 0040 §5) is reified by
    // the `domaintypes` op; seed it only when absent (mirrors `domain.ts`) so the
    // `meta()` import resolves before the first reification.
    let meta_ts = nano.join("meta.ts");
    if !meta_ts.exists() {
        std::fs::write(&meta_ts, META_TS_STUB)?;
    }
    std::fs::write(nano.join("node-loader.mjs"), NODE_LOADER_MJS)?;
    std::fs::write(nano.join("node-register.mjs"), NODE_REGISTER_MJS)?;
    std::fs::write(nano.join("node-deno-shim.mjs"), NODE_DENO_SHIM_MJS)?;
    std::fs::write(nano.join("llm-worker.ts"), LLM_WORKER_TS)?;
    std::fs::write(nano.join("worker-sdk.ts"), WORKER_SDK_TS)?;
    // Seed the standard-tooling config (VS Code / `tsc`) and the Node-first
    // project manifest for projects scaffolded before these existed. Seed-once so
    // a maker's own `tsconfig.json`/`package.json` edits (extra deps, options)
    // survive SDK re-materialisation.
    let tsconfig = dir.join("tsconfig.json");
    if !tsconfig.exists() {
        std::fs::write(&tsconfig, gendir(PROJECT_TSCONFIG_JSON))?;
    }
    let package_json = dir.join("package.json");
    if !package_json.exists() {
        std::fs::write(&package_json, project_package_json(name))?;
    }
    Ok(())
}

/// Errors from the datasource gateway, mapped to HTTP status by the caller.
#[derive(Debug)]
pub enum DataError {
    /// The project name doesn't resolve to a directory.
    NoProject,
    /// No JavaScript runtime (Node >= 22.6 or Deno) is available to host the
    /// datasource seam.
    NoRuntime,
    /// The subprocess failed to spawn or produced unparseable output.
    Gateway(String),
    /// The datasource operation itself returned `{ ok: false, error }`
    /// (bad SQL, unknown source, missing manifest, …).
    Op(String),
}

/// Run one datasource operation for `project` by invoking the materialised
/// `nano-generated/data-cli.ts` under Deno (or the Node >= 22.6 fallback, ADR 0036/
/// 0037; ADR 0024 §4). The panel's every read/write
/// goes through this one seam so it targets whatever the named datasource
/// resolves to — SQLite today, a server driver once a `nano-ide-data-*` pack is
/// installed — never a parallel SQLite-only path. `request` is the CLI's JSON
/// protocol object (`{ op, source?, sql?, params? }`); the resolved result
/// object is returned on success.
pub async fn run_data_op(
    project: &str,
    request: serde_json::Value,
) -> Result<serde_json::Value, DataError> {
    use tokio::io::AsyncWriteExt;

    let mut request = request;
    let dir = project_dir(project).ok_or(DataError::NoProject)?;
    if !dir.is_dir() {
        return Err(DataError::NoProject);
    }
    // Model-first envelope IO (ADR 0040 slices 1–2 / ADR 0033 §6 increment 12):
    // the BPMN model is the source of truth for the data-envelope maps, so for the
    // reifying op we scan the project's process models once and inject both
    // `derivedWorkers` (`taskType -> {in,out}`), `derivedMessages`
    // (`messageName -> {in,out}`), and `derivedShapes` (composed `nano:shape`
    // declarations, ADR 0040 §9/§10). The reifier overlays the workers on the
    // manifest `workers[]`, emits the typed message registry, and resolves each
    // shape through the fuse into a `DomainTypes` entry, so `worker-io.d.ts` /
    // `message-io.d.ts` / `domain-rows.d.ts` reflect the model, not a
    // hand-maintained projection that can drift.
    if request.get("op").and_then(|v| v.as_str()) == Some("domaintypes")
        && let Some(obj) = request.as_object_mut()
    {
        // Scan only when at least one derived map is missing: the `domaintypes`
        // preview (ADR 0040 §9/§10) supplies all four (its in-editor
        // `derivedShapes`/`derivedMeta` plus empty `derivedWorkers`/`derivedMessages`,
        // which it does not need), so the latency-sensitive preview path skips reading
        // every `resources/processes/*.bpmn` on each debounced keystroke.
        let needs_scan = [
            "derivedWorkers",
            "derivedMessages",
            "derivedShapes",
            "derivedMeta",
        ]
        .iter()
        .any(|k| !obj.contains_key(*k));
        if needs_scan {
            let scan = super::envelope_scan::scan_project(&dir);
            // Insert each map only when the caller did not already supply it: the
            // preview POSTs the in-editor `derivedShapes` so its live field
            // preview/diagnostics reflect *unsaved* composer edits, and must win
            // over the saved-model scan.
            if !obj.contains_key("derivedWorkers") {
                obj.insert(
                    "derivedWorkers".to_string(),
                    serde_json::to_value(scan.workers).unwrap_or(serde_json::Value::Null),
                );
            }
            if !obj.contains_key("derivedMessages") {
                obj.insert(
                    "derivedMessages".to_string(),
                    serde_json::to_value(scan.messages).unwrap_or(serde_json::Value::Null),
                );
            }
            if !obj.contains_key("derivedShapes") {
                obj.insert(
                    "derivedShapes".to_string(),
                    serde_json::to_value(scan.shapes).unwrap_or(serde_json::Value::Null),
                );
            }
            if !obj.contains_key("derivedMeta") {
                obj.insert(
                    "derivedMeta".to_string(),
                    serde_json::to_value(scan.meta).unwrap_or(serde_json::Value::Null),
                );
            }
        }
    }
    // The gateway runs the data CLI Node-first: Node (>= 22.6) is always present
    // (the npm launcher is Node), so it is the primary path; Deno is an equal
    // alternative. Both the CLI and the `@nanobpm/data` SDK carry the runtime
    // shim, so the Data panel works with only Node installed. See ADR 0038/0036.
    enum CliRuntime {
        Deno(std::path::PathBuf),
        Node(std::path::PathBuf),
    }
    let runtime = if let Some(n) = workers::usable_node() {
        CliRuntime::Node(n)
    } else if let Some(d) = workers::find_deno() {
        CliRuntime::Deno(d)
    } else {
        return Err(DataError::NoRuntime);
    };
    ensure_project_sdk(project).map_err(|e| DataError::Gateway(format!("materialise SDK: {e}")))?;

    // Canonicalize so the --allow-read/-write scope matches the path Deno
    // resolves (e.g. macOS /tmp -> /private/tmp); otherwise findManifest can't
    // read nano.app.json and every op fails with "manifest not found".
    let dir = std::fs::canonicalize(&dir).unwrap_or(dir);
    let cache = dir.join(".deno-cache");
    let _ = std::fs::create_dir_all(&cache);
    let cli = dir.join(GEN_DIR).join("data-cli.ts");

    let mut cmd = match &runtime {
        CliRuntime::Deno(deno) => {
            let mut c = Command::new(deno);
            c.current_dir(&dir)
                .arg("run")
                .arg("--no-prompt")
                .arg(format!("--allow-read={}", dir.display()))
                .arg(format!("--allow-write={}", dir.display()))
                .arg("--allow-env")
                .arg(&cli)
                .env("DENO_DIR", &cache);
            c
        }
        CliRuntime::Node(node) => {
            // Node fallback: strip TS types + register the import-map loader
            // (materialised in nano-generated/ by ensure_project_sdk) so the CLI's
            // `./data-sdk.ts` and `node:sqlite` specifiers resolve. Node has no
            // capability sandbox; the gateway only touches the project dir.
            let mut c = Command::new(node);
            c.current_dir(&dir)
                .arg("--experimental-strip-types")
                .arg("--no-warnings")
                .arg("--import")
                .arg(dir.join(GEN_DIR).join("node-register.mjs"))
                .arg(&cli);
            c
        }
    };
    cmd.env("NO_COLOR", "1")
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);

    let mut child = cmd
        .spawn()
        .map_err(|e| DataError::Gateway(format!("spawn data gateway: {e}")))?;
    let body = serde_json::to_vec(&request).unwrap_or_default();
    if let Some(mut stdin) = child.stdin.take() {
        stdin
            .write_all(&body)
            .await
            .map_err(|e| DataError::Gateway(format!("write request: {e}")))?;
        // Drop stdin (via scope) so the CLI's stdin reader sees EOF.
    }
    let out = child
        .wait_with_output()
        .await
        .map_err(|e| DataError::Gateway(format!("await deno: {e}")))?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        return Err(DataError::Gateway(format!(
            "deno exited {}: {}",
            out.status,
            err.trim()
        )));
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let mut val: serde_json::Value = serde_json::from_str(text.trim())
        .map_err(|e| DataError::Gateway(format!("bad gateway output: {e}: {}", text.trim())))?;
    let ok = val.get("ok").and_then(|v| v.as_bool()).unwrap_or(false);
    if !ok {
        let msg = val
            .get("error")
            .and_then(|v| v.as_str())
            .unwrap_or("datasource operation failed")
            .to_string();
        return Err(DataError::Op(msg));
    }
    if let Some(obj) = val.as_object_mut() {
        obj.remove("ok");
    }
    Ok(val)
}

/// `template` selects which starter content to stamp out ("starter" default, or
/// "throughput" for the benchmark demo). Unknown templates fall back to starter.
pub fn create_project(
    name: &str,
    description: &str,
    template: &str,
) -> Result<ProjectConfig, String> {
    let dir = project_dir(name).ok_or("invalid project name")?;
    // A name that already has an import reference (ADR 0041) — even a dangling
    // one — is taken. Never let `create_project` scaffold into a ref's external
    // target: refuse here and write only within the projects root.
    if read_project_ref(name).is_some() {
        return Err("a project with that name already exists".into());
    }
    if dir.exists() {
        return Err("a project with that name already exists".into());
    }
    let mk = |p: PathBuf| std::fs::create_dir_all(&p).map_err(|e| format!("create {p:?}: {e}"));

    // ── Pack template short-circuit ───────────────────────────────────────
    // If `template` names an installed pack template (or an example pack's
    // own id), stamp out ONLY that pack's contents. The Deno-flavoured
    // built-in files below would otherwise leak into a Java/Rust/etc.
    // project — the caller ended up with a Deno starter with pack files
    // sprinkled on top, and any BPMN the pack shipped got shadowed by
    // resources/processes/*.bpmn from the built-in fallthrough.
    let is_builtin_template = matches!(
        template,
        "starter"
            | "throughput"
            | "throughput-stream"
            | "gui-starter"
            | "urban-starter"
            | "workflow-starter"
    );
    if !is_builtin_template && let Some((m, src)) = super::extensions::template_source(template) {
        mk(dir.clone())?;
        super::extensions::copy_tree(&src, &dir).map_err(|e| format!("copy pack template: {e}"))?;
        // The project's `lang` drives the run/compile toolchain (lang_pack lookup):
        // a LANG pack's own template implies the pack itself; app/example packs
        // name their language via `requires` (first entry = the lang pack id).
        // Only with neither do we fall back to the built-in Deno runtime.
        let cfg_lang = if m.kind == super::extensions::ExtKind::Lang {
            m.id.clone()
        } else {
            m.requires
                .first()
                .cloned()
                .unwrap_or_else(|| "deno".to_string())
        };
        // Best-effort detection of the "main" entrypoint the console
        // surfaces in the workspace toolbar. Ordered from most specific
        // to least so multi-module Java packs prefer the actual module
        // POM over an aggregator root POM. `is_file()` (not `exists()`)
        // so a same-named directory can't masquerade as the entrypoint.
        let candidates: &[&str] = &[
            "src/main.rs",
            "microservice/pom.xml",
            "app/pom.xml",
            "pom.xml",
            "main.ts",
        ];
        let cfg_main = candidates
            .iter()
            .find(|c| dir.join(c).is_file())
            .map(|c| c.to_string())
            .unwrap_or_else(|| "main.ts".to_string());
        let mut cfg = ProjectConfig::new(name, description);
        cfg.lang = cfg_lang;
        cfg.app = "console".to_string();
        cfg.main = cfg_main;
        // Snapshot the pack's toolchain into the project so pack updates or
        // uninstalls don't break existing projects — the project owns its
        // run/compile invocation from this point on.
        if !m.toolchain.run.is_empty()
            || !m.toolchain.compile.is_empty()
            || !m.toolchain.run_configs.is_empty()
        {
            cfg.toolchain = Some(project_toolchain_from_pack(&m));
        }
        cfg.scaffolded_from = Some(ScaffoldedFrom {
            pack: m.id.clone(),
            version: super::extensions::pack_version(&m.id),
        });
        cfg.template = Some(template.to_string());
        write_config(name, &cfg).map_err(|e| format!("write config: {e}"))?;
        return Ok(cfg);
    }

    // ── Code-first workflow scaffold (ADR 0045) ───────────────────────────
    // A code-first project has NO authored BPMN and none of the model-first
    // `nano-generated/` machinery below: the executable model is DERIVED from
    // the workflow code by @nanobpm/workflow at deploy time. Stamp a lean tree
    // and return before the model-first built-ins.
    if template == "workflow-starter" {
        mk(dir.join("workflows"))?;
        mk(dir.join("scripts"))?;
        let w = |p: PathBuf, body: &str| {
            std::fs::write(&p, body).map_err(|e| format!("write {p:?}: {e}"))
        };
        w(dir.join("deno.json"), WORKFLOW_DENO_JSON)?;
        w(dir.join("tsconfig.json"), WORKFLOW_TSCONFIG_JSON)?;
        w(dir.join("package.json"), &workflow_package_json(name))?;
        w(dir.join("main.ts"), WORKFLOW_MAIN_TS)?;
        w(
            dir.join("workflows").join("pr-review.ts"),
            WORKFLOW_EXAMPLE_TS,
        )?;
        w(
            dir.join("scripts").join("start-instance.ts"),
            WORKFLOW_START_INSTANCE_TS,
        )?;
        w(dir.join("scripts").join("approve.ts"), WORKFLOW_APPROVE_TS)?;
        w(dir.join("README.md"), &workflow_readme(name))?;
        let mut cfg = ProjectConfig::new(name, description);
        cfg.lang = "deno".to_string();
        cfg.app = "console".to_string();
        cfg.main = "main.ts".to_string();
        cfg.template = Some("workflow-starter".to_string());
        write_config(name, &cfg).map_err(|e| format!("write config: {e}"))?;
        return Ok(cfg);
    }

    // ── Built-in (Deno-flavoured) scaffolds ───────────────────────────────
    mk(dir.join("resources").join("processes"))?;
    mk(dir.join("resources").join("decisions"))?;
    mk(dir.join("resources").join("forms"))?;
    mk(dir.join("lib"))?;
    mk(dir.join(GEN_DIR))?;

    let w =
        |p: PathBuf, body: &str| std::fs::write(&p, body).map_err(|e| format!("write {p:?}: {e}"));
    w(dir.join("deno.json"), &gendir(PROJECT_DENO_JSON))?;
    w(dir.join("tsconfig.json"), &gendir(PROJECT_TSCONFIG_JSON))?;
    w(dir.join("package.json"), &project_package_json(name))?;
    w(dir.join(GEN_DIR).join("data-sdk.ts"), DATA_SDK_TS)?;
    w(dir.join(GEN_DIR).join("app-pages.ts"), APP_PAGES_TS)?;
    w(dir.join(GEN_DIR).join("data-cli.ts"), DATA_CLI_TS)?;
    w(dir.join(GEN_DIR).join("domain-types.ts"), DOMAIN_TYPES_TS)?;
    w(dir.join(GEN_DIR).join("domain.ts"), DOMAIN_TS_STUB)?;
    w(dir.join(GEN_DIR).join("workers.ts"), WORKERS_TS)?;
    w(dir.join(GEN_DIR).join("worker-io.d.ts"), WORKERS_DTS_STUB)?;
    w(dir.join(GEN_DIR).join("messages.ts"), MESSAGES_TS)?;
    w(dir.join(GEN_DIR).join("message-io.d.ts"), MESSAGES_DTS_STUB)?;
    w(dir.join(GEN_DIR).join("meta.ts"), META_TS_STUB)?;
    w(dir.join(GEN_DIR).join("node-loader.mjs"), NODE_LOADER_MJS)?;
    w(
        dir.join(GEN_DIR).join("node-register.mjs"),
        NODE_REGISTER_MJS,
    )?;
    w(
        dir.join(GEN_DIR).join("node-deno-shim.mjs"),
        NODE_DENO_SHIM_MJS,
    )?;
    w(dir.join(GEN_DIR).join("worker-sdk.ts"), WORKER_SDK_TS)?;
    w(dir.join(GEN_DIR).join("llm-worker.ts"), LLM_WORKER_TS)?;
    w(dir.join("lib").join("nano.ts"), NANO_LIB_TS)?;

    // All remaining built-in scaffolds are Deno-flavoured (Rust/Java are
    // pack-provided), so lang/main are fixed; only `gui-starter` varies `app`.
    let cfg_lang = "deno".to_string();
    let mut cfg_app = "console";
    let cfg_main = "main.ts".to_string();

    if template == "throughput" {
        let worker = dir.join("workers").join("tick");
        mk(worker.clone())?;
        w(dir.join("main.ts"), DEMO_MAIN_TS)?;
        w(dir.join("README.md"), &demo_readme())?;
        w(
            dir.join("resources")
                .join("processes")
                .join("throughput.bpmn"),
            DEMO_PROCESS_BPMN,
        )?;
        w(worker.join("worker.ts"), DEMO_WORKER_TS)?;
        w(worker.join("deno.json"), &gendir(WORKER_DENO_JSON))?;
    } else if template == "throughput-stream" {
        w(dir.join("deno.json"), &gendir(DEMO_STREAM_DENO_JSON))?;
        w(dir.join("main.ts"), DEMO_STREAM_MAIN_TS)?;
        w(dir.join("README.md"), &demo_stream_readme())?;
        w(
            dir.join("resources")
                .join("processes")
                .join("throughput.bpmn"),
            DEMO_PROCESS_BPMN,
        )?;
    } else if template == "gui-starter" {
        mk(dir.join("public"))?;
        w(dir.join("deno.json"), &gendir(GUI_DENO_JSON))?;
        w(dir.join("main.ts"), GUI_MAIN_TS)?;
        w(dir.join("public").join("index.html"), GUI_INDEX_HTML)?;
        w(dir.join("README.md"), &gui_readme(name))?;
        w(
            dir.join("resources")
                .join("processes")
                .join(format!("{name}.bpmn")),
            &starter_process(name),
        )?;
        cfg_app = "deno-gui";
    } else if template == "urban-starter" {
        mk(dir.join("pages"))?;
        mk(dir.join("db").join("migrations"))?;
        let app_id = slugify_app_id(name);
        w(dir.join("deno.json"), &gendir(URBAN_DENO_JSON))?;
        w(dir.join("main.ts"), URBAN_MAIN_TS)?;
        w(dir.join("nano.app.json"), &urban_manifest(&app_id, name))?;
        w(
            dir.join("pages").join("home.page.json"),
            &urban_home_page(name),
        )?;
        w(dir.join("README.md"), &urban_readme(name))?;
        w(
            dir.join("resources")
                .join("processes")
                .join(format!("{name}.bpmn")),
            &starter_process(name),
        )?;
        mk(dir.join("components"))?;
        w(
            dir.join("components").join("read-thermostat.json"),
            URBAN_COMPONENT_READ_THERMOSTAT,
        )?;
        w(
            dir.join("components").join("classify-llm.json"),
            URBAN_COMPONENT_CLASSIFY_LLM,
        )?;
        cfg_app = "urban";
    } else {
        let starter_worker = dir.join("workers").join("do-work");
        mk(starter_worker.clone())?;
        w(dir.join("main.ts"), MAIN_TS)?;
        w(dir.join("README.md"), &readme_md(name))?;
        w(
            dir.join("resources")
                .join("processes")
                .join(format!("{name}.bpmn")),
            &starter_process(name),
        )?;
        w(starter_worker.join("worker.ts"), STARTER_WORKER_TS)?;
        w(starter_worker.join("deno.json"), &gendir(WORKER_DENO_JSON))?;
    }

    let mut cfg = ProjectConfig::new(name, description);
    cfg.lang = cfg_lang;
    cfg.app = cfg_app.to_string();
    cfg.main = cfg_main;
    // Record which built-in template was stamped out. Unknown ids fall through
    // to the "starter" scaffold above, so that's what we record. `scaffolded_from`
    // stays None here — its absence is how the Console distinguishes a built-in
    // template from a pack-contributed one.
    cfg.template = Some(
        if matches!(
            template,
            "throughput" | "throughput-stream" | "gui-starter" | "urban-starter"
        ) {
            template
        } else {
            "starter"
        }
        .to_string(),
    );
    write_config(name, &cfg).map_err(|e| format!("write config: {e}"))?;
    Ok(cfg)
}

/// Deletes a project directory and everything in it.
pub fn delete_project(name: &str) -> std::io::Result<()> {
    let dir = project_dir(name).ok_or_else(|| {
        std::io::Error::new(std::io::ErrorKind::InvalidInput, "invalid project name")
    })?;
    // A real workspace directory shadows any reference (matching `project_dir`),
    // so delete it. Also drop a coexisting ref so the name can't silently
    // resurrect as an imported project once its directory is gone.
    let workspace_dir = projects_root().join(name);
    if workspace_dir.is_dir() {
        // Drop a coexisting ref before removing the directory; propagate an IO
        // error so a pointer that can't be removed can't silently resurrect the
        // name later (fail closed).
        remove_project_ref(name)?;
        return std::fs::remove_dir_all(workspace_dir);
    }
    // A pure imported-by-reference project (ADR 0041) owns only its pointer file
    // — deleting it must remove the reference, never the external checkout.
    if remove_project_ref(name)? {
        return Ok(());
    }
    std::fs::remove_dir_all(dir)
}

/// Renames a project directory and updates its persisted config name. Fails if
/// the source is missing, the target name is unsafe, or the target exists. The
/// caller must ensure the project is stopped first.
pub fn rename_project(old: &str, new: &str) -> Result<ProjectConfig, String> {
    if !workspace::is_safe_name(new) {
        return Err("invalid new name".into());
    }
    if !workspace::is_safe_name(old) {
        return Err("invalid project name".into());
    }
    // Rename is workspace-scoped: it moves a real directory under the projects
    // root. Compute both endpoints from the root — never `project_dir`, whose
    // ref resolution could point `to` (a dangling `new` reference) at an
    // external path and move the workspace project outside the root.
    let from = projects_root().join(old);
    if !from.is_dir() {
        // A pure imported-by-reference project (no workspace dir) can't be
        // renamed by a directory move; remove and re-import under the new name.
        if read_project_ref(old).is_some() {
            return Err(
                "cannot rename an imported-by-reference project; remove and re-import".into(),
            );
        }
        return Err("no such project".into());
    }
    // Refuse renaming *into* any referenced name (even a dangling ref) — that
    // name is taken, and letting the move win would shadow the pointer.
    if read_project_ref(new).is_some() {
        return Err("a project with that name already exists".into());
    }
    let to = projects_root().join(new);
    if to.exists() {
        return Err("a project with that name already exists".into());
    }
    std::fs::rename(&from, &to).map_err(|e| format!("rename: {e}"))?;
    // Drop any ref coexisting with `old` so the moved-away name can't resurrect
    // as an imported project once its directory is gone (fail closed).
    remove_project_ref(old).map_err(|e| format!("remove reference: {e}"))?;
    let mut cfg = read_config(new).ok_or("config missing after rename")?;
    cfg.name = new.to_string();
    cfg.updated_ms = now_ms();
    write_config(new, &cfg).map_err(|e| format!("write config: {e}"))?;
    Ok(cfg)
}

