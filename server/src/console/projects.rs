    /// End-to-end datasource gateway: materialise a project, run migrations,
    /// then schema/query/exec through the real `data-cli.ts` against an embedded
    /// SQLite file (ADR 0024 §4). Runtime-agnostic (ADR 0038): runs under Node
    /// (preferred) or Deno; skipped only when neither is present (CI). The SDK
    /// internals are covered locally by `data_sdk_test.ts`.
    #[tokio::test]
    #[allow(clippy::await_holding_lock)] // serialises on the shared PROJECTS_DIR env; guard must span the run_data_op awaits
    async fn run_data_op_roundtrips_through_the_data_gateway() {
        let _g = lock();
        if workers::usable_node().is_none() && workers::find_deno().is_none() {
            eprintln!("skipping: no JS runtime (Node >= 22.6 or Deno) installed");
            return;
        }
        let root = temp_root();
        let name = "dsapp";
        let dir = root.join(name);
        std::fs::create_dir_all(dir.join("db/migrations")).unwrap();
        std::fs::write(
            dir.join("nano.app.json"),
            r#"{ "data": { "default": "app", "sources": {
                "app": { "driver": "sqlite", "url": "file:./app.db", "migrations": "db/migrations" }
            } } }"#,
        )
        .unwrap();
        std::fs::write(
            dir.join("db/migrations/001_init.sql"),
            "CREATE TABLE orders (id INTEGER PRIMARY KEY, name TEXT NOT NULL);\n\
             CREATE TABLE lines (id INTEGER PRIMARY KEY, order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE);\n\
             INSERT INTO orders (name) VALUES ('first');",
        )
        .unwrap();
        ensure_project_sdk(name).unwrap();

        // sources: the declared alias, resolved.
        let src = run_data_op(name, serde_json::json!({ "op": "sources" }))
            .await
            .expect("sources");
        assert_eq!(src["default"], "app");
        assert_eq!(src["sources"][0]["driver"], "sqlite");

        // migrate: applies the one pending file.
        let mig = run_data_op(name, serde_json::json!({ "op": "migrate" }))
            .await
            .expect("migrate");
        assert_eq!(mig["applied"], serde_json::json!(["001_init.sql"]));

        // migrations status now reports it applied.
        let ms = run_data_op(name, serde_json::json!({ "op": "migrations" }))
            .await
            .expect("migrations");
        assert_eq!(ms["entries"][0]["applied"], true);

        // schema sees the user table.
        let sc = run_data_op(name, serde_json::json!({ "op": "schema" }))
            .await
            .expect("schema");
        let tables: Vec<String> = sc["tables"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t["name"].as_str().unwrap().to_string())
            .collect();
        assert!(tables.contains(&"orders".to_string()));

        // schema also surfaces foreign keys (ADR 0024 structure-editor support):
        // the `lines.order_id` FK targets `orders(id)` with ON DELETE CASCADE.
        let lines = sc["tables"]
            .as_array()
            .unwrap()
            .iter()
            .find(|t| t["name"] == "lines")
            .expect("lines table");
        let fk = &lines["foreignKeys"][0];
        assert_eq!(fk["column"], "order_id");
        assert_eq!(fk["refTable"], "orders");
        assert_eq!(fk["refColumn"], "id");
        assert_eq!(fk["onDelete"], "CASCADE");

        // exec + query roundtrip a parameterised insert.
        let ex = run_data_op(
            name,
            serde_json::json!({ "op": "exec", "sql": "INSERT INTO orders (name) VALUES (?)", "params": ["second"] }),
        )
        .await
        .expect("exec");
        assert_eq!(ex["changed"], 1);

        let q = run_data_op(
            name,
            serde_json::json!({ "op": "query", "sql": "SELECT name FROM orders ORDER BY id" }),
        )
        .await
        .expect("query");
        assert_eq!(q["columns"], serde_json::json!(["name"]));
        assert_eq!(q["rows"][0]["name"], "first");
        assert_eq!(q["rows"][1]["name"], "second");

        // A bad statement surfaces as an Op error (→ 400), not a gateway crash.
        let err = run_data_op(
            name,
            serde_json::json!({ "op": "query", "sql": "SELECT * FROM nope" }),
        )
        .await;
        assert!(matches!(err, Err(DataError::Op(_))));

        // script: several statements run atomically (a SQLite-style table
        // rebuild). Here we add a column via a rebuild and preserve the data.
        let sc = run_data_op(
            name,
            serde_json::json!({ "op": "script", "statements": [
                "CREATE TABLE orders__new (id INTEGER PRIMARY KEY, name TEXT NOT NULL, qty INTEGER)",
                "INSERT INTO orders__new (id, name) SELECT id, name FROM orders",
                "DROP TABLE orders",
                "ALTER TABLE orders__new RENAME TO orders",
            ] }),
        )
        .await
        .expect("script");
        assert!(sc["changed"].as_i64().unwrap() >= 2); // at least the two rows copied

        let q = run_data_op(
            name,
            serde_json::json!({ "op": "query", "sql": "SELECT name, qty FROM orders ORDER BY id" }),
        )
        .await
        .expect("query after rebuild");
        assert_eq!(q["rows"][0]["name"], "first");
        assert_eq!(q["rows"][0]["qty"], serde_json::Value::Null);

        // script rolls back on a mid-script failure: the first statement would
        // succeed alone, but the second is invalid, so neither is committed.
        let err = run_data_op(
            name,
            serde_json::json!({ "op": "script", "statements": [
                "CREATE TABLE rollback_probe (id INTEGER PRIMARY KEY)",
                "THIS IS NOT SQL",
            ] }),
        )
        .await;
        assert!(matches!(err, Err(DataError::Op(_))));
        let gone = run_data_op(
            name,
            serde_json::json!({ "op": "query", "sql": "SELECT 1 FROM sqlite_master WHERE name='rollback_probe'" }),
        )
        .await
        .expect("probe query");
        assert!(gone["rows"].as_array().unwrap().is_empty());
    }

