#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectSummary {
    pub name: String,
    pub description: String,
    pub deploy_target: String,
    pub updated_ms: u64,
    pub processes: usize,
    pub decisions: usize,
    pub forms: usize,
    pub workers: usize,
    pub running: bool,
    /// Where the project lives: `"workspace"` (a directory under the projects
    /// root) or `"path"` (an external directory imported by reference, ADR 0041).
    pub source: String,
    /// Language pack id (from the project config; default "deno"). The Console
    /// resolves the card's language icon by matching this to a lang Extension.
    pub lang: String,
    /// Scaffold template id, when recorded. Absent on projects created before
    /// this breadcrumb existed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub template: Option<String>,
    /// Pack that scaffolded the project, when it came from an installed pack.
    /// Absent for built-in templates (the `template` id alone then identifies
    /// the built-in scaffold).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub scaffolded_from: Option<ScaffoldedFrom>,
}

fn count_ext(dir: &Path, ext: &str) -> usize {
    std::fs::read_dir(dir)
        .map(|rd| {
            rd.flatten()
                .filter(|e| e.path().extension().map(|x| x == ext).unwrap_or(false))
                .count()
        })
        .unwrap_or(0)
}

fn count_dirs(dir: &Path) -> usize {
    std::fs::read_dir(dir)
        .map(|rd| rd.flatten().filter(|e| e.path().is_dir()).count())
        .unwrap_or(0)
}

/// Lists every project (each subdirectory of the projects root). `running` is
/// left `false` here; the handler fills it from the supervisor.
pub fn list_projects() -> std::io::Result<Vec<ProjectSummary>> {
    let root = ensure_projects_root()?;
    let mut out = Vec::new();
    for entry in std::fs::read_dir(&root)?.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if name.starts_with('.') || !workspace::is_safe_name(name) {
            continue;
        }
        let cfg = read_config(name).unwrap_or_else(|| ProjectConfig::new(name, ""));
        let res = path.join("resources");
        out.push(ProjectSummary {
            name: name.to_string(),
            description: cfg.description,
            deploy_target: cfg.deploy_target,
            updated_ms: cfg.updated_ms,
            processes: count_ext(&res.join("processes"), "bpmn"),
            decisions: count_ext(&res.join("decisions"), "dmn"),
            forms: count_ext(&res.join("forms"), "form"),
            workers: count_dirs(&path.join("workers")),
            running: false,
            source: "workspace".to_string(),
            lang: cfg.lang,
            template: cfg.template,
            scaffolded_from: cfg.scaffolded_from,
        });
    }
    // Imported-by-reference projects (ADR 0041): `<name>.project-ref.json` files
    // in the projects root that resolve to an external directory, read live.
    for entry in std::fs::read_dir(&root)?.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let Some(name) = path
            .file_name()
            .and_then(|n| n.to_str())
            .and_then(|f| f.strip_suffix(".project-ref.json"))
        else {
            continue;
        };
        if !workspace::is_safe_name(name) {
            continue;
        }
        // A real workspace directory shadows a reference of the same name
        // (matching `project_dir`), so don't emit a duplicate `path` tile for a
        // ref that the resolver ignores.
        if root.join(name).is_dir() {
            continue;
        }
        let Some(dir) = project_dir(name) else {
            continue;
        };
        // A dangling pointer (the external checkout moved/was removed) is still
        // surfaced so the operator can see and fix it, rather than vanishing.
        if !dir.is_dir() {
            out.push(ProjectSummary {
                name: name.to_string(),
                description: "(source not found)".to_string(),
                deploy_target: default_deploy_target(),
                updated_ms: 0,
                processes: 0,
                decisions: 0,
                forms: 0,
                workers: 0,
                running: false,
                source: "path".to_string(),
                lang: "deno".to_string(),
                template: None,
                scaffolded_from: None,
            });
            continue;
        }
        let cfg = read_config(name).unwrap_or_else(|| ProjectConfig::new(name, ""));
        let res = dir.join("resources");
        out.push(ProjectSummary {
            name: name.to_string(),
            description: cfg.description,
            deploy_target: cfg.deploy_target,
            updated_ms: cfg.updated_ms,
            processes: count_ext(&res.join("processes"), "bpmn"),
            decisions: count_ext(&res.join("decisions"), "dmn"),
            forms: count_ext(&res.join("forms"), "form"),
            workers: count_dirs(&dir.join("workers")),
            running: false,
            source: "path".to_string(),
            lang: cfg.lang,
            template: cfg.template,
            scaffolded_from: cfg.scaffolded_from,
        });
    }
    out.sort_by(|a, b| b.updated_ms.cmp(&a.updated_ms).then(a.name.cmp(&b.name)));
    Ok(out)
}

