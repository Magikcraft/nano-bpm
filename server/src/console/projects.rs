#[derive(Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
enum Phase {
    Stopped,
    Starting,
    Running,
    Crashed,
}

/// A single log line from a project's run/compile output.
#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct LogLine {
    pub ts_ms: u64,
    /// `out` (stdout), `err` (stderr), or `sys` (supervisor notes).
    pub stream: String,
    pub text: String,
}

/// Runtime view of one project's run state.
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RunStateDto {
    status: Phase,
    pid: Option<u32>,
    started_at_ms: Option<u64>,
    last_error: Option<String>,
    /// Whether a compile is currently in progress.
    compiling: bool,
}

struct ProjectInner {
    phase: Mutex<Phase>,
    last_error: Mutex<Option<String>>,
    started_at_ms: Mutex<Option<u64>>,
    pid: AtomicU32,
    desired_running: AtomicBool,
    compiling: AtomicBool,
    stop: Notify,
    logs_tx: broadcast::Sender<LogLine>,
    log_ring: Mutex<VecDeque<LogLine>>,
}

impl ProjectInner {
    fn new() -> Arc<Self> {
        let (logs_tx, _) = broadcast::channel(256);
        Arc::new(Self {
            phase: Mutex::new(Phase::Stopped),
            last_error: Mutex::new(None),
            started_at_ms: Mutex::new(None),
            pid: AtomicU32::new(0),
            desired_running: AtomicBool::new(false),
            compiling: AtomicBool::new(false),
            stop: Notify::new(),
            logs_tx,
            log_ring: Mutex::new(VecDeque::with_capacity(LOG_RING_CAP)),
        })
    }

    async fn push_log(&self, stream: &str, text: String) {
        let line = LogLine {
            ts_ms: now_ms(),
            stream: stream.to_string(),
            text,
        };
        {
            let mut ring = self.log_ring.lock().await;
            if ring.len() >= LOG_RING_CAP {
                ring.pop_front();
            }
            ring.push_back(line.clone());
        }
        let _ = self.logs_tx.send(line);
    }

    /// Interpret one line of a run's stdout. Swallows the per-worker `METRIC`
    /// telemetry the embedded SDK emits every second, unwraps `STATUS` control
    /// lines into human-readable `sys` log entries, and passes everything else
    /// through as `out`. Shared by both run paths (`run` built-in and
    /// `run_toolchain`) so their consoles surface identical output.
    async fn ingest_stdout_line(&self, line: String) {
        // `BufReader::lines()` strips `\n` but leaves a trailing `\r` on CRLF
        // producers; drop it so STATUS JSON still parses and logs carry no stray
        // carriage return.
        let line = match line.strip_suffix('\r') {
            Some(trimmed) => trimmed.to_string(),
            None => line,
        };
        if line.starts_with(METRIC_PREFIX) {
            return; // per-worker metric telemetry — not shown
        }
        if let Some(rest) = line.strip_prefix(STATUS_PREFIX) {
            let msg = serde_json::from_str::<serde_json::Value>(rest)
                .ok()
                .map(|v| {
                    format!(
                        "{}: {}",
                        v.get("state").and_then(|s| s.as_str()).unwrap_or("status"),
                        v.get("message").and_then(|s| s.as_str()).unwrap_or("")
                    )
                })
                .unwrap_or_else(|| rest.to_string());
            self.push_log("sys", msg).await;
        } else {
            self.push_log("out", line).await;
        }
    }

    async fn dto(&self) -> RunStateDto {
        let pid = self.pid.load(Ordering::Relaxed);
        RunStateDto {
            status: *self.phase.lock().await,
            pid: (pid != 0).then_some(pid),
            started_at_ms: *self.started_at_ms.lock().await,
            last_error: self.last_error.lock().await.clone(),
            compiling: self.compiling.load(Ordering::Relaxed),
        }
    }
}

