/// A node in the project file tree.
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FileNode {
    /// Display name (the last path segment).
    pub name: String,
    /// Project-relative path (`/`-separated).
    pub path: String,
    /// `"dir"` or `"file"`.
    pub kind: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub children: Option<Vec<FileNode>>,
}

/// Hidden / generated entries never shown in the browser.
fn is_hidden(name: &str) -> bool {
    name.starts_with('.') || name == "node_modules"
}

fn read_tree(dir: &Path, rel: &str) -> Vec<FileNode> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .map(|rd| rd.flatten().collect())
        .unwrap_or_default();
    entries.sort_by_key(|e| {
        let p = e.path();
        // Directories first, then alphabetical.
        (!p.is_dir(), e.file_name().to_string_lossy().to_lowercase())
    });
    let mut out = Vec::new();
    for entry in entries {
        let name = entry.file_name().to_string_lossy().to_string();
        if is_hidden(&name) {
            continue;
        }
        let child_rel = if rel.is_empty() {
            name.clone()
        } else {
            format!("{rel}/{name}")
        };
        let path = entry.path();
        if path.is_dir() {
            out.push(FileNode {
                children: Some(read_tree(&path, &child_rel)),
                name,
                path: child_rel,
                kind: "dir",
            });
        } else {
            out.push(FileNode {
                name,
                path: child_rel,
                kind: "file",
                children: None,
            });
        }
    }
    out
}

/// Builds the recursive file tree for a project (excluding hidden/generated
/// entries), or `None` when the project does not exist.
pub fn file_tree(name: &str) -> Option<Vec<FileNode>> {
    let dir = project_dir(name)?;
    if !dir.is_dir() {
        return None;
    }
    Some(read_tree(&dir, ""))
}

